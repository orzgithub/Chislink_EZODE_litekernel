uint8_t savemode_lookup(const uint8_t gamecode[4])
{
    uint32_t key = ((uint32_t)gamecode[0] << 24) | ((uint32_t)gamecode[1] << 16) |
                   ((uint32_t)gamecode[2] << 8) | (uint32_t)gamecode[3];
    uint32_t i;
    /* the kernel table is not sorted (the original does a linear scan), so do
     * the same: 1600 comparisons is cheap compared to file I/O. */
    for (i = 0; i < (uint32_t)(sizeof(s_modes) / sizeof(s_modes[0])); ++i) {
        if (s_codes[i] == key) {
            return s_modes[i];
        }
    }
    return 0x10;
}

uint32_t savemode_size(uint8_t mode)
{
    switch (mode) {
    case 0x00: return 0;
    case 0x11: return 0x8000;
    case 0x21: return 0x200;
    case 0x22:
    case 0x23: return 0x2000;
    case 0x31: return 0x20000;
    case 0x32:
    case 0x33: return 0x10000;
    case 0xee: return 0x10000;
    default:   return 0x10000;
    }
}
